use anyhow::{Context, bail, ensure};
use serde_json::Value;

use crate::policy::{ClientTarget, Policy};
use crate::schema::{Document, EnumValues, Field, Model, TypeKind, TypeRef, Union};

const HEADER: &str = "// swiftlint:disable all\n// Code generated by newsly-contract-codegen. Do not edit.\nimport Foundation\n\n";

pub(crate) fn render_enums(
    document: &Document,
    policy: &Policy,
    target: ClientTarget,
) -> anyhow::Result<String> {
    let mut output = String::from(HEADER);
    for item in policy.enums.iter().filter(|item| item.includes(target)) {
        let name = item.swift_name();
        let section = match document.enum_values(&item.schema)? {
            EnumValues::Strings(values) => render_string_enum(&name, &values, item.open),
            EnumValues::Integers(values) => {
                ensure!(
                    !item.open,
                    "open integer enum {} is unsupported",
                    item.schema
                );
                render_int_enum(&name, &values)
            }
        };
        output.push_str(&section);
        output.push('\n');
    }
    Ok(output.trim_end().to_owned() + "\n")
}

pub(crate) fn render_models(
    document: &Document,
    policy: &Policy,
    target: ClientTarget,
) -> anyhow::Result<String> {
    let mut output = String::from(HEADER);
    for union in document.unions_for_target(policy, target)? {
        output.push_str(&render_union(&union, policy));
        output.push('\n');
    }
    for model in document.models_for_target(policy, target)? {
        output.push_str(&render_model(&model, policy, target)?);
        output.push('\n');
    }
    Ok(output.trim_end().to_owned() + "\n")
}

fn render_union(union: &Union, policy: &Policy) -> String {
    let name = policy.swift_type_name(&union.name);
    let case_names = union
        .variants
        .iter()
        .map(|variant| swift_case_name(&variant.tag))
        .collect::<Vec<_>>();
    let unknown = unique_unknown_case(&case_names);
    let key = swift_identifier(&snake_to_lower_camel(&union.discriminator));
    let mut lines = vec![format!("enum {name}: Codable {{")];
    for (variant, case_name) in union.variants.iter().zip(&case_names) {
        lines.push(format!(
            "    case {}({})",
            case_name,
            policy.swift_type_name(&variant.model)
        ));
    }
    lines.extend([
        format!("    case {unknown}(String, AnyCodable)"),
        String::new(),
        "    private enum DiscriminatorKey: String, CodingKey {".to_owned(),
        format!("        case {key} = {}", quoted(&union.discriminator)),
        "    }".to_owned(),
        String::new(),
        "    init(from decoder: Decoder) throws {".to_owned(),
        "        let container = try decoder.container(keyedBy: DiscriminatorKey.self)".to_owned(),
        format!("        let discriminator = try container.decode(String.self, forKey: .{key})"),
        "        switch discriminator {".to_owned(),
    ]);
    for (variant, case_name) in union.variants.iter().zip(&case_names) {
        lines.push(format!(
            "        case {}: self = .{}(try {}(from: decoder))",
            quoted(&variant.tag),
            case_name,
            policy.swift_type_name(&variant.model)
        ));
    }
    lines.extend([
        format!("        default: self = .{unknown}(discriminator, try AnyCodable(from: decoder))"),
        "        }".to_owned(),
        "    }".to_owned(),
        String::new(),
        "    func encode(to encoder: Encoder) throws {".to_owned(),
        "        switch self {".to_owned(),
    ]);
    for (variant, case_name) in union.variants.iter().zip(&case_names) {
        lines.extend([
            format!("        case .{case_name}(let payload):"),
            "            try payload.encode(to: encoder)".to_owned(),
            "            var container = encoder.container(keyedBy: DiscriminatorKey.self)"
                .to_owned(),
            format!(
                "            try container.encode({}, forKey: .{key})",
                quoted(&variant.tag)
            ),
        ]);
    }
    lines.extend([
        format!("        case .{unknown}(let discriminator, let payload):"),
        "            try payload.encode(to: encoder)".to_owned(),
        "            var container = encoder.container(keyedBy: DiscriminatorKey.self)".to_owned(),
        format!("            try container.encode(discriminator, forKey: .{key})"),
        "        }".to_owned(),
        "    }".to_owned(),
        "}".to_owned(),
    ]);
    lines.join("\n") + "\n"
}

fn unique_unknown_case(known: &[String]) -> String {
    let mut candidate = "unknown".to_owned();
    while known.contains(&candidate) {
        candidate.push_str("Raw");
    }
    candidate
}

fn render_string_enum(name: &str, values: &[String], open: bool) -> String {
    if open {
        return render_open_string_enum(name, values);
    }
    let mut lines = vec![format!("enum {name}: String, Codable, CaseIterable {{")];
    for value in values {
        lines.push(format!(
            "    case {} = {}",
            swift_case_name(value),
            quoted(value)
        ));
    }
    lines.push("}".to_owned());
    lines.join("\n") + "\n"
}

fn render_open_string_enum(name: &str, values: &[String]) -> String {
    let unknown = if values.iter().any(|value| value == "unknown") {
        "unknownRaw"
    } else {
        "unknown"
    };
    let mut lines = vec![format!("enum {name}: Codable, Equatable, Hashable {{")];
    for value in values {
        lines.push(format!("    case {}", swift_case_name(value)));
    }
    lines.push(format!("    case {unknown}(String)"));
    lines.extend([
        String::new(),
        format!("    static let knownCases: [{name}] = ["),
    ]);
    for value in values {
        lines.push(format!("        .{},", swift_case_name(value)));
    }
    lines.extend([
        "    ]".to_owned(),
        String::new(),
        "    var rawValue: String {".to_owned(),
        "        switch self {".to_owned(),
    ]);
    for value in values {
        lines.push(format!(
            "        case .{}: {}",
            swift_case_name(value),
            quoted(value)
        ));
    }
    lines.extend([
        format!("        case .{unknown}(let rawValue): rawValue"),
        "        }".to_owned(),
        "    }".to_owned(),
        String::new(),
        "    init(rawValue: String) {".to_owned(),
        "        switch rawValue {".to_owned(),
    ]);
    for value in values {
        lines.push(format!(
            "        case {}: self = .{}",
            quoted(value),
            swift_case_name(value)
        ));
    }
    lines.extend([
        format!("        default: self = .{unknown}(rawValue)"),
        "        }".to_owned(),
        "    }".to_owned(),
        String::new(),
        "    init(from decoder: Decoder) throws {".to_owned(),
        "        let container = try decoder.singleValueContainer()".to_owned(),
        "        self.init(rawValue: try container.decode(String.self))".to_owned(),
        "    }".to_owned(),
        String::new(),
        "    func encode(to encoder: Encoder) throws {".to_owned(),
        "        var container = encoder.singleValueContainer()".to_owned(),
        "        try container.encode(rawValue)".to_owned(),
        "    }".to_owned(),
        "}".to_owned(),
    ]);
    lines.join("\n") + "\n"
}

fn render_int_enum(name: &str, values: &[i64]) -> String {
    let mut lines = vec![format!("enum {name}: Int, Codable, CaseIterable {{")];
    for value in values {
        lines.push(format!("    case v{value} = {value}"));
    }
    lines.push("}".to_owned());
    lines.join("\n") + "\n"
}

fn render_model(model: &Model, policy: &Policy, target: ClientTarget) -> anyhow::Result<String> {
    let name = policy.model_policy(&model.name).map_or_else(
        || format!("API{}", strip_dto_suffix(&model.name)),
        super::policy::ModelPolicy::swift_name,
    );
    let fields = model
        .fields
        .iter()
        .map(|field| SwiftField::new(model, field, policy, target))
        .collect::<anyhow::Result<Vec<_>>>()?;
    let mut lines = vec![format!("struct {name}: Codable {{")];
    for field in &fields {
        lines.push(format!("    let {}: {}", field.name, field.type_name));
    }
    lines.push(String::new());
    lines.extend(render_memberwise_init(&fields));
    lines.extend([
        String::new(),
        "    enum CodingKeys: String, CodingKey {".to_owned(),
    ]);
    for field in &fields {
        lines.push(format!(
            "        case {} = {}",
            field.name,
            quoted(&field.wire_name)
        ));
    }
    lines.extend(["    }".to_owned(), String::new()]);
    lines.extend(render_decoder(&fields)?);
    lines.push(String::new());
    lines.extend(render_encoder(&fields));
    lines.push("}".to_owned());
    Ok(lines.join("\n") + "\n")
}

#[derive(Debug)]
struct SwiftField {
    path: String,
    name: String,
    wire_name: String,
    type_name: String,
    decode_type: String,
    presence: WirePresence,
    datetime: bool,
    lenient: bool,
    default_expr: Option<String>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
enum WirePresence {
    Required,
    RequiredNullable,
    Optional,
    OptionalNullable,
}

impl WirePresence {
    const fn new(required: bool, nullable: bool) -> Self {
        match (required, nullable) {
            (true, false) => Self::Required,
            (true, true) => Self::RequiredNullable,
            (false, false) => Self::Optional,
            (false, true) => Self::OptionalNullable,
        }
    }

    const fn is_nullable(self) -> bool {
        matches!(self, Self::RequiredNullable | Self::OptionalNullable)
    }

    const fn requires_key(self) -> bool {
        matches!(self, Self::Required | Self::RequiredNullable)
    }
}

impl SwiftField {
    fn new(
        model: &Model,
        field: &Field,
        policy: &Policy,
        target: ClientTarget,
    ) -> anyhow::Result<Self> {
        let path = format!("{}.{}", model.name, field.wire_name);
        let decode_type = swift_non_optional_type(&field.type_ref, policy, target)?;
        let presence = WirePresence::new(field.required, field.type_ref.nullable);
        let type_name = if presence.is_nullable() {
            format!("{decode_type}?")
        } else {
            decode_type.clone()
        };
        let default_expr = default_expr(field, &path, &decode_type, policy)?;
        let lenient = policy.settings.lenient_fields.contains(&path);
        if lenient {
            ensure!(
                default_expr.is_some(),
                "{path}: lenient Swift decoding requires a default"
            );
        }
        Ok(Self {
            path,
            name: swift_identifier(&snake_to_lower_camel(&field.wire_name)),
            wire_name: field.wire_name.clone(),
            type_name,
            decode_type,
            presence,
            datetime: matches!(field.type_ref.kind, TypeKind::DateTime),
            lenient,
            default_expr,
        })
    }
}

fn render_memberwise_init(fields: &[SwiftField]) -> Vec<String> {
    let mut lines = vec!["    init(".to_owned()];
    for (index, field) in fields.iter().enumerate() {
        let comma = if index + 1 == fields.len() { "" } else { "," };
        let default = field
            .default_expr
            .as_ref()
            .map_or_else(String::new, |value| format!(" = {value}"));
        lines.push(format!(
            "        {}: {}{}{}",
            field.name, field.type_name, default, comma
        ));
    }
    lines.push("    ) {".to_owned());
    for field in fields {
        lines.push(format!("        self.{0} = {0}", field.name));
    }
    lines.push("    }".to_owned());
    lines
}

fn render_decoder(fields: &[SwiftField]) -> anyhow::Result<Vec<String>> {
    let mut lines = vec![
        "    init(from decoder: Decoder) throws {".to_owned(),
        "        let container = try decoder.container(keyedBy: CodingKeys.self)".to_owned(),
    ];
    for field in fields {
        if field.datetime {
            lines.extend(render_datetime_decode(field)?);
        } else if field.lenient {
            let default = field
                .default_expr
                .as_deref()
                .with_context(|| format!("{}: lenient field has no default", field.path))?;
            lines.push(format!(
                "        {} = try container.decodeIfPresent({}.self, forKey: .{}) ?? {}",
                field.name, field.decode_type, field.name, default
            ));
        } else if field.presence.is_nullable() && field.presence.requires_key() {
            lines.push(format!(
                "        {} = try container.decode({}.self, forKey: .{})",
                field.name, field.type_name, field.name
            ));
        } else if field.presence.is_nullable() {
            lines.push(format!(
                "        {} = try container.decodeIfPresent({}.self, forKey: .{})",
                field.name, field.decode_type, field.name
            ));
        } else {
            lines.push(format!(
                "        {} = try container.decode({}.self, forKey: .{})",
                field.name, field.decode_type, field.name
            ));
        }
    }
    lines.push("    }".to_owned());
    Ok(lines)
}

fn render_datetime_decode(field: &SwiftField) -> anyhow::Result<Vec<String>> {
    let raw = format!("{}Raw", field.name.trim_matches('`'));
    let parsed = format!("{}Parsed", field.name.trim_matches('`'));
    let error = format!(
        "DecodingError.dataCorruptedError(forKey: .{}, in: container, debugDescription: {})",
        field.name,
        quoted(&format!(
            "Unparseable date for {}",
            field.name.trim_matches('`')
        ))
    );
    if field.lenient {
        let default = field
            .default_expr
            .as_deref()
            .with_context(|| format!("{}: lenient datetime has no default", field.path))?;
        return Ok(vec![
            format!(
                "        if let {raw} = try container.decodeIfPresent(String.self, forKey: .{}), let {parsed} = ServerDate.parse({raw}) {{",
                field.name
            ),
            format!("            {} = {parsed}", field.name),
            "        } else {".to_owned(),
            format!("            {} = {default}", field.name),
            "        }".to_owned(),
        ]);
    }
    if field.presence.is_nullable() && field.presence.requires_key() {
        return Ok(vec![
            format!(
                "        if let {raw} = try container.decode(String?.self, forKey: .{}) {{",
                field.name
            ),
            format!("            guard let {parsed} = ServerDate.parse({raw}) else {{"),
            format!("                throw {error}"),
            "            }".to_owned(),
            format!("            {} = {parsed}", field.name),
            "        } else {".to_owned(),
            format!("            {} = nil", field.name),
            "        }".to_owned(),
        ]);
    }
    if field.presence.is_nullable() {
        return Ok(vec![
            format!(
                "        if let {raw} = try container.decodeIfPresent(String.self, forKey: .{}) {{",
                field.name
            ),
            format!("            guard let {parsed} = ServerDate.parse({raw}) else {{"),
            format!("                throw {error}"),
            "            }".to_owned(),
            format!("            {} = {parsed}", field.name),
            "        } else {".to_owned(),
            format!("            {} = nil", field.name),
            "        }".to_owned(),
        ]);
    }
    Ok(vec![
        format!(
            "        let {raw} = try container.decode(String.self, forKey: .{})",
            field.name
        ),
        format!("        guard let {parsed} = ServerDate.parse({raw}) else {{"),
        format!("            throw {error}"),
        "        }".to_owned(),
        format!("        {} = {parsed}", field.name),
    ])
}

fn render_encoder(fields: &[SwiftField]) -> Vec<String> {
    let mut lines = vec![
        "    func encode(to encoder: Encoder) throws {".to_owned(),
        "        var container = encoder.container(keyedBy: CodingKeys.self)".to_owned(),
    ];
    for field in fields {
        if field.datetime && field.presence.is_nullable() && field.presence.requires_key() {
            lines.push(format!(
                "        try container.encode({}.map(ServerDate.format), forKey: .{})",
                field.name, field.name
            ));
        } else if field.datetime && field.presence.is_nullable() {
            lines.push(format!(
                "        try container.encodeIfPresent({}.map(ServerDate.format), forKey: .{})",
                field.name, field.name
            ));
        } else if field.datetime {
            lines.push(format!(
                "        try container.encode(ServerDate.format({}), forKey: .{})",
                field.name, field.name
            ));
        } else if field.presence.is_nullable() && field.presence.requires_key() {
            lines.push(format!(
                "        try container.encode({}, forKey: .{})",
                field.name, field.name
            ));
        } else if field.presence.is_nullable() {
            lines.push(format!(
                "        try container.encodeIfPresent({}, forKey: .{})",
                field.name, field.name
            ));
        } else {
            lines.push(format!(
                "        try container.encode({}, forKey: .{})",
                field.name, field.name
            ));
        }
    }
    lines.push("    }".to_owned());
    lines
}

fn swift_non_optional_type(
    type_ref: &TypeRef,
    policy: &Policy,
    target: ClientTarget,
) -> anyhow::Result<String> {
    let base = match &type_ref.kind {
        TypeKind::String => "String".to_owned(),
        TypeKind::Integer => "Int".to_owned(),
        TypeKind::Float => "Double".to_owned(),
        TypeKind::Boolean => "Bool".to_owned(),
        TypeKind::DateTime => "Date".to_owned(),
        TypeKind::Untyped => "AnyCodable".to_owned(),
        TypeKind::Enum(name) => {
            let enum_policy = policy
                .enum_policy(name)
                .with_context(|| format!("referenced enum {name} is not registered"))?;
            ensure!(
                enum_policy.includes(target),
                "referenced enum {name} is not emitted for {target:?}"
            );
            enum_policy.swift_name()
        }
        TypeKind::Model(name) | TypeKind::Union(name) => policy.swift_type_name(name),
        TypeKind::List(item) => {
            ensure!(
                !contains_datetime(item),
                "nested datetime containers require a dedicated Swift codec"
            );
            format!("[{}]", swift_type(item, policy, target)?)
        }
        TypeKind::Map(item) => {
            ensure!(
                !contains_datetime(item),
                "nested datetime containers require a dedicated Swift codec"
            );
            format!("[String: {}]", swift_type(item, policy, target)?)
        }
    };
    Ok(base)
}

fn swift_type(type_ref: &TypeRef, policy: &Policy, target: ClientTarget) -> anyhow::Result<String> {
    let base = swift_non_optional_type(type_ref, policy, target)?;
    Ok(if type_ref.nullable {
        format!("{base}?")
    } else {
        base
    })
}

fn contains_datetime(type_ref: &TypeRef) -> bool {
    match &type_ref.kind {
        TypeKind::DateTime => true,
        TypeKind::List(item) | TypeKind::Map(item) => contains_datetime(item),
        _ => false,
    }
}

fn default_expr(
    field: &Field,
    path: &str,
    decode_type: &str,
    policy: &Policy,
) -> anyhow::Result<Option<String>> {
    if field.type_ref.nullable {
        return Ok(
            (!field.required || policy.settings.lenient_fields.contains(path))
                .then(|| "nil".to_owned()),
        );
    }
    let explicit = policy
        .field_default(path)?
        .or_else(|| field.schema_default.clone());
    if let Some(value) = explicit {
        return render_default(&value, &field.type_ref, decode_type).map(Some);
    }
    if field.required && !policy.settings.lenient_fields.contains(path) {
        return Ok(None);
    }
    Ok(match field.type_ref.kind {
        TypeKind::String => Some(quoted("")),
        TypeKind::Integer | TypeKind::Float => Some("0".to_owned()),
        TypeKind::Boolean => Some("false".to_owned()),
        TypeKind::List(_) => Some("[]".to_owned()),
        TypeKind::Map(_) | TypeKind::Untyped => Some("[:]".to_owned()),
        TypeKind::DateTime | TypeKind::Enum(_) | TypeKind::Model(_) | TypeKind::Union(_) => None,
    })
}

fn render_default(value: &Value, type_ref: &TypeRef, decode_type: &str) -> anyhow::Result<String> {
    match (&type_ref.kind, value) {
        (TypeKind::Enum(_), Value::String(value)) => Ok(format!(".{}", swift_case_name(value))),
        (TypeKind::String, Value::String(value)) => Ok(quoted(value)),
        (TypeKind::Boolean, Value::Bool(value)) => Ok(value.to_string()),
        (TypeKind::Integer | TypeKind::Float, Value::Number(value)) => Ok(value.to_string()),
        (TypeKind::List(_), Value::Array(items)) if items.is_empty() => Ok("[]".to_owned()),
        (TypeKind::Map(_), Value::Object(items)) if items.is_empty() => Ok("[:]".to_owned()),
        _ => bail!("unsupported Swift default {value} for {decode_type}"),
    }
}

fn quoted(value: &str) -> String {
    serde_json::to_string(value).expect("serializing a Rust string to JSON cannot fail")
}

fn swift_case_name(value: &str) -> String {
    value.replace('-', "_")
}

fn snake_to_lower_camel(value: &str) -> String {
    let mut parts = value.split('_');
    let mut output = parts.next().unwrap_or_default().to_owned();
    for part in parts {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            output.extend(first.to_uppercase());
            output.extend(chars);
        }
    }
    output
}

fn strip_dto_suffix(value: &str) -> &str {
    value.strip_suffix("Dto").unwrap_or(value)
}

fn swift_identifier(value: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "associatedtype",
        "class",
        "deinit",
        "enum",
        "extension",
        "fileprivate",
        "func",
        "import",
        "init",
        "inout",
        "internal",
        "let",
        "open",
        "operator",
        "private",
        "protocol",
        "public",
        "static",
        "struct",
        "subscript",
        "typealias",
        "var",
        "break",
        "case",
        "catch",
        "continue",
        "default",
        "defer",
        "do",
        "else",
        "fallthrough",
        "for",
        "guard",
        "if",
        "in",
        "repeat",
        "return",
        "switch",
        "where",
        "while",
    ];
    if KEYWORDS.contains(&value) {
        format!("`{value}`")
    } else {
        value.to_owned()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lower_camel_preserves_wire_words() {
        assert_eq!(snake_to_lower_camel("request_id"), "requestId");
        assert_eq!(snake_to_lower_camel("url"), "url");
    }

    #[test]
    fn open_enum_preserves_unknown_wire_values() {
        let output =
            render_open_string_enum("APIStatus", &["ready".to_owned(), "unknown".to_owned()]);
        assert!(output.contains("case unknownRaw(String)"));
        assert!(output.contains("default: self = .unknownRaw(rawValue)"));
    }
}
