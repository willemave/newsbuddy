"""Compile synthetic YAML state to reviewable, transactional PostgreSQL SQL.

This module knows fixture inserts, never production retrieval or migration policy.
"""

from __future__ import annotations

import json
import re
from datetime import UTC
from typing import Any

from newsly_evals.chat.schema import Scenario


def literal(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    text = str(value)
    if "\x00" in text:
        raise ValueError("PostgreSQL text cannot contain NUL")
    return "'" + text.replace("'", "''") + "'"


def fixture_url(value: str, namespace: str) -> str:
    return value.replace("{namespace}", namespace)


def generate_sql(scenario: Scenario, namespace: str) -> str:
    if not re.fullmatch(r"[a-z][a-z0-9-]{0,47}", namespace):
        raise ValueError("namespace must contain 1-48 lowercase letters, digits or hyphens")
    lines = [
        "-- Generated by newsly-evals chat generate. Apply only to a disposable eval DB.",
        "\\set ON_ERROR_STOP on",
        "BEGIN;",
        "SET LOCAL standard_conforming_strings = on;",
        "DO $$ BEGIN IF current_database() !~ '^newsly_eval_[a-z0-9_]+$' THEN",
        "RAISE EXCEPTION 'fixture SQL requires a newsly_eval_* database'; END IF; END $$;",
        "CREATE TEMP TABLE eval_refs (key text PRIMARY KEY, id bigint) ON COMMIT DROP;",
    ]

    def ref(kind: str, name: str) -> str:
        return f"(SELECT id FROM eval_refs WHERE key={literal(kind + ':' + name)})"

    def insert(table: str, fields: dict[str, str], key: str | None = None) -> None:
        statement = (
            f"INSERT INTO {table} ({', '.join(fields)}) VALUES ({', '.join(fields.values())})"
        )
        if key:
            statement = (
                f"WITH inserted AS ({statement} RETURNING id) "
                f"INSERT INTO eval_refs SELECT {literal(key)}, id FROM inserted"
            )
        lines.append(statement + ";")

    for key, account in scenario.users.items():
        insert(
            "users",
            {
                "apple_id": literal(f"eval_{namespace}_{key}"),
                "email": literal(f"{namespace}.{key}@eval.example.test"),
                "full_name": literal(account.name),
                "is_admin": "FALSE",
                "is_active": "TRUE",
                "has_completed_onboarding": "TRUE",
            },
            f"user:{key}",
        )
        insert(
            "chat_sessions",
            {
                "user_id": ref("user", key),
                "title": literal(f"Eval {namespace}"),
                "session_type": literal("knowledge_chat"),
                "council_mode": "FALSE",
                "is_hidden_from_history": "FALSE",
            },
            f"session:{key}",
        )
    for key, feed in scenario.feeds.items():
        for user in feed.users:
            insert(
                "user_scraper_configs",
                {
                    "user_id": ref("user", user),
                    "scraper_type": literal("podcast_rss"),
                    "display_name": literal(feed.title),
                    "feed_url": literal(fixture_url(feed.url, namespace)),
                    "config": literal(json.dumps({"name": feed.title})),
                },
                f"feed:{key}:{user}",
            )
    for key, episode in scenario.episodes.items():
        date = episode.published_at.astimezone(UTC).isoformat()
        metadata = {
            "feed_url": fixture_url(scenario.feeds[episode.feed].url, namespace),
            "fixture_namespace": namespace,
            "transcript": episode.body,
            "summary": {
                "title": episode.title,
                "overview": episode.body,
                "full_markdown": episode.body,
            },
        }
        insert(
            "contents",
            {
                "content_type": literal("podcast"),
                "url": literal(fixture_url(episode.url, namespace)),
                "source_url": literal(fixture_url(episode.url, namespace)),
                "title": literal(episode.title),
                "source": literal(scenario.feeds[episode.feed].title),
                "status": literal("completed"),
                "classification": literal("to_read"),
                "is_aggregate": "FALSE",
                "platform": literal("podcast"),
                "publication_date": literal(date),
                "created_at": literal(date),
                "processed_at": literal(date),
                "content_metadata": literal(json.dumps(metadata)),
                "search_text": literal(episode.title + " " + episode.body),
            },
            f"episode:{key}",
        )
        for user in episode.visible_to:
            insert(
                "content_status",
                {
                    "user_id": ref("user", user),
                    "content_id": ref("episode", key),
                    "status": literal("inbox"),
                },
            )
        for table, users in [
            ("content_read_status", episode.read_by),
            ("content_knowledge_saves", episode.saved_by),
        ]:
            for user in users:
                insert(table, {"user_id": ref("user", user), "content_id": ref("episode", key)})
    lines.extend(["SELECT json_object_agg(key, id) FROM eval_refs;", "COMMIT;", ""])
    return "\n".join(lines)
